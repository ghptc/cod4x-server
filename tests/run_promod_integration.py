#!/usr/bin/env python3
"""Actual isolated engine/Promod qualification; synthetic human commands via test plugin.
Requires a freshly prepared private runtime and reviewed catalog/workspace checkouts.
Never operates on an existing runtime or any remote host.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import secrets
import shutil
import socket
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--runtime', type=Path, required=True)
p.add_argument('--game', type=Path, required=True)
p.add_argument('--catalog', type=Path, required=True)
p.add_argument('--workspace', type=Path, required=True)
a = p.parse_args()
assert (a.runtime / '.bot-test-runtime').is_file()
def load_script(name):
    spec = importlib.util.spec_from_file_location('qualification_' + name, a.workspace / 'scripts' / (name + '.py'))
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module
runtime_policy = load_script('runtime')
mode_policy = load_script('modes')
fs_game, startup_map, fingerprint, maps_csv, capacity, _ = mode_policy.select(a.catalog, 'promod')
home = Path(tempfile.mkdtemp(prefix='cod4x-promod-integration-'))
for name in ('mods', 'integrity'):
    shutil.copytree(a.runtime / name, home / name)
for name in ('main', 'zone'):
    (home / name).symlink_to((a.game / name).resolve(), target_is_directory=True)
shutil.copy2(ROOT / 'bin/cod4x18_dedrun', home / 'cod4x18_dedrun')
mod = home / 'mods/pml220'
shutil.copy2(a.catalog / 'shared/server.cfg', mod / 'canonical-shared.cfg')
shutil.copy2(a.catalog / 'modes/promod/server.cfg', mod / 'canonical-mode.cfg')
with (mod / 'canonical-shared.cfg').open('a') as stream:
    stream.write('\nset promod_allow_no_punkbuster "1"\n')
shutil.copy2(ROOT / 'tests/promod_runtime.gsc', mod / 'maps/mp/bots/integration_test.gsc')
for wrapper in (mod / 'maps/mp').glob('mp_*.gsx'):
    wrapper.write_text(wrapper.read_text().replace('main(){', 'main(){level thread maps\\mp\\bots\\integration_test::init();', 1))
(home / 'plugins').mkdir()
subprocess.run(['cc', '-m32', '-shared', '-fPIC', str(ROOT / 'tests/promod_runtime_plugin.c'),
                '-o', str(home / 'plugins/runtime_test.so')], check=True)
password = secrets.token_hex(20)
# Obsolete private rules and a nested exec must not win over mode-owned values.
(mod / 'private.cfg').write_text(f'set rcon_password "{password}"\nset sv_wwwBaseURL "http://127.0.0.1/local-fixture"\nexec obsolete.cfg\n')
(mod / 'obsolete.cfg').write_text('set sv_mapRotation "gametype sd map mp_crash"\n'
    'set sv_mapRotationCurrent "gametype sd map mp_crash"\nset sv_randomMapRotation "0"\n'
    'set sv_pure "0"\nset g_allowVote "0"\nset promod_auto_maprotate "0"\nset promod_mode "custom_public"\n')
checks = {}; snapshots = []
for attempt in range(2):
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as channel:
        channel.bind(('127.0.0.1', 0)); port = channel.getsockname()[1]
    service = {'entrypoint': [runtime_policy.EXECUTABLE],
        'volumes': [{'target': value} for value in ('/home/user/cod4/main', '/home/user/cod4/zone', runtime_policy.PERSISTENT_HOME)],
        'command': ['+set', 'dedicated', '1', '+set', 'net_ip', '127.0.0.1',
            '+set', 'net_port', str(port), '+set', 'fs_homepath', runtime_policy.PERSISTENT_HOME,
            '+set', 'sv_pure', '1', '+set', 'bot_enable', '1', '+set', 'bot_debug', '1',
            '+exec', 'private.cfg', '+map', 'mp_crash']}
    managed = runtime_policy.adapt(service, 'qualification-only', 'promod', fingerprint,
                                   fs_game, startup_map, maps_csv, capacity)['command']
    # Translate only the qualified managed filesystem roots for a host-local
    # disposable process. Command ordering is generated by the production adapter.
    cmd = [str(home / 'cod4x18_dedrun')] + [value.replace(runtime_policy.ARTIFACT_ROOT, str(home)).replace(
        runtime_policy.PERSISTENT_HOME, str(home)) for value in managed]
    output = (home / f'console-{attempt}.log').open('w')
    proc = subprocess.Popen(cmd, cwd=home, stdin=subprocess.PIPE, stdout=output, stderr=subprocess.STDOUT)
    def send(command):
        assert proc.poll() is None, 'engine exited; inspect ' + str(home)
        proc.stdin.write((command + '\n').encode()); proc.stdin.flush()
    def rcon(command, credential=password):
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as channel:
            channel.settimeout(3)
            channel.sendto(b'\xff' * 4 + f'rcon {credential} {command}'.encode(), ('127.0.0.1', port))
            return re.sub(r'\^[0-9]', '', channel.recv(65535).decode(errors='replace'))
    def snap(tag):
        send('set integration_snapshot ""\nset integration_request ' + tag)
        deadline = time.monotonic() + 3
        while time.monotonic() < deadline:
            game = rcon('integration_snapshot')
            found = list(re.finditer(r'PROMOD_RUNTIME ' + tag + r' map=(\w+) over=(\d+) bots=(\d+) bot_ready=(\d+) humans=(\d+) human_ready=(\d+) phase=(\w+) rounds=(-?\d+) eligible=(\d+) pending=(\d+) rdyup=(\d+)', game))
            if found:
                values = found[-1].groups()
                data = dict(zip(('map', 'over', 'bots', 'bot_ready', 'humans', 'human_ready', 'phase', 'rounds', 'eligible', 'pending', 'rdyup'), values))
                for key in data.keys() - {'map', 'phase'}: data[key] = int(data[key])
                snapshots.append(dict(tag=tag, **data)); return data
            time.sleep(.05)
        raise AssertionError('snapshot timed out: ' + tag)
    try:
        time.sleep(4)
        checks[f'cfg_precedence_{attempt}'] = ('mp_vacant' in rcon('sv_mapRotation') and
            '"1"' in rcon('g_allowVote') and '"match_mr12_pb"' in rcon('promod_mode') and
            '"1"' in rcon('sv_randomMapRotation') and '"1"' in rcon('promod_auto_maprotate'))
        checks[f'private_environment_{attempt}'] = 'http://127.0.0.1/local-fixture' in rcon('sv_wwwBaseURL')
        time.sleep(8)
        first = snap('startup' + str(attempt))
        checks[f'bot_only_readyup_{attempt}'] = first['rdyup'] == 1 and first['bots'] == 12 and first['over'] == 0 and first['bot_ready'] == 0
        if attempt == 1:
            send('bot_limit 0')
            maps = re.search(r'set sv_mapRotation "([^"]+)"',
                (a.catalog / 'modes/promod/server.cfg').read_text())[1].split()[3::4]
            for index, mapname in enumerate(maps):
                send('map ' + mapname); time.sleep(1)
                state = snap('qualified_map_' + str(index))
                checks['installed_map_' + mapname] = (state['map'] == mapname and
                    '"1"' in rcon('g_allowVote') and '"1"' in rcon('bot_ai_ready'))
            continue
        # Real UDP admission into a full bot lobby, separate from active-client
        # synthetic fixtures below. It does not enter the graphical game world.
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as human:
            human.bind(('127.0.0.2', 0)); human.settimeout(3)
            human.sendto(b'\xff' * 4 + b'getchallenge 123456', ('127.0.0.1', port))
            challenge = human.recv(2048)[4:].decode().split()[1]
            payload = f'connect "\\protocol\\21\\challenge\\{challenge}\\qport\\24444\\name\\AdmissionFixture\\rate\\25000\\snaps\\20"'
            human.sendto(b'\xff' * 4 + payload.encode(), ('127.0.0.1', port))
            checks['real_human_handshake'] = b'connectResponse' in human.recv(2048)
            time.sleep(.2)
            status = rcon('bot_status')
            checks['human_replaces_bot'] = 'humans=1' in status and 'bots=11' in status
            send('clientkick 0')
        time.sleep(.2)
        send('loadplugin runtime_test')
        time.sleep(.5)
        # Re-enter ordinary mode initialization with an initially empty lobby.
        send('bot_kickall\nmap_restart')
        time.sleep(22)
        send('bot_add 1'); time.sleep(.35)
        send('runtime_fixture 0 human'); time.sleep(.15)
        snap('reset_human'); time.sleep(2)
        held = snap('human_unready')
        checks['human_blocks_readyup'] = held['humans'] == 1 and held['human_ready'] == 0 and held['over'] == 0
        send('bot_add 3'); time.sleep(2)
        mixed = snap('mixed_unready')
        checks['bots_excluded_human_unready'] = mixed['bot_ready'] == 0 and mixed['bots'] == 3 and mixed['pending'] == 1 and mixed['over'] == 0
        snap('team_reset'); time.sleep(.2)
        checks['team_change_clears_ready'] = snap('team_cleared')['bot_ready'] == 0
        snap('team_restore'); time.sleep(.2)
        checks['bot_team_restore_still_excluded'] = snap('team_restored')['bot_ready'] == 0
        snap('recorded')
        send('runtime_fixture 0 use 1'); time.sleep(.3); send('runtime_fixture 0 use 0')
        time.sleep(.2)
        readyup = snap('human_ready')
        checks['human_use_readyup'] = readyup['human_ready'] == 1
        send('runtime_fixture 0 bot')
        time.sleep(7)
        ready = snap('mixed_playing')
        send('runtime_fixture 0 human\nruntime_fixture 1 human\nruntime_fixture 2 human')
        # Actual native client command path and CheckVote, on live game entities.
        send('runtime_fixture 3 callvote mp_strike')
        time.sleep(.15)
        console = (home / 'console-0.log').read_text(errors='replace')
        checks['bot_cannot_callvote'] = bool(re.search(r'slot=3 human=0 voteTime=0', console))
        send('runtime_fixture 0 callvote mp_invalid'); time.sleep(.15)
        checks['invalid_map_rejected'] = 'voteTime=0' in (home / 'console-0.log').read_text(errors='replace').split('RUNTIME_FIXTURE')[-1]
        target = 'mp_strike' if ready['map'] != 'mp_strike' else 'mp_backlot'
        vote_called_at = time.monotonic()
        send('runtime_fixture 0 callvote ' + target); time.sleep(.2)
        checks['three_human_vote_waits'] = '""' in rcon('g_votedMapName')
        send('runtime_fixture 3 vote yes'); time.sleep(.1)
        send('runtime_fixture 1 vote yes'); time.sleep(4)
        checks['human_vote_passes'] = f'"{target}"' in rcon('g_votedMapName')
        cooldown = int(re.search(r'"g_voteCooldown" is: "(\d+)', rcon('g_voteCooldown'))[1])
        if time.monotonic() - vote_called_at < cooldown - .25:
            send('runtime_fixture 2 callvote ' + target); time.sleep(.1)
            event = (home / 'console-0.log').read_text(errors='replace').split('RUNTIME_FIXTURE')[-1]
            checks['live_cooldown_before_expiry'] = bool(re.search(r'slot=2 human=1 voteTime=0', event))
        while time.monotonic() - vote_called_at < cooldown + .25:
            time.sleep(min(1, cooldown + .25 - (time.monotonic() - vote_called_at)))
        vote_called_at = time.monotonic()
        send('runtime_fixture 2 callvote ' + target); time.sleep(.1)
        event = (home / 'console-0.log').read_text(errors='replace').split('RUNTIME_FIXTURE')[-1]
        checks['live_cooldown_after_expiry'] = bool(re.search(r'slot=2 human=1 voteTime=[1-9]\d*', event))
        send('runtime_fixture 1 vote yes'); time.sleep(4)
        checks['vote_waits_match_end'] = snap('voted_before_end')['map'] == ready['map']
        send('runtime_fixture 0 bot\nruntime_fixture 1 bot\nruntime_fixture 2 bot')
        snap('short_match')
        send('runtime_fixture 0 eliminate axis'); time.sleep(12)
        round1 = snap('round_one')
        checks['round_keeps_map'] = round1['map'] == ready['map']
        snap('short_match')
        send('runtime_fixture 0 eliminate axis'); time.sleep(24)
        ended = snap('match_end')
        checks['match_uses_vote'] = ended['map'] == target and '""' in rcon('g_votedMapName')
        checks['voting_survives_map'] = '"1"' in rcon('g_allowVote') and 'mp_vacant' in rcon('sv_mapRotation')
        send('bot_add 3'); time.sleep(8)
        send('bots_play_fire 0\nruntime_fixture 0 human')
        second_target = 'mp_backlot' if ended['map'] != 'mp_backlot' else 'mp_strike'
        cooldown = int(re.search(r'"g_voteCooldown" is: "(\d+)', rcon('g_voteCooldown'))[1])
        if time.monotonic() - vote_called_at < cooldown - 1:
            send('runtime_fixture 0 callvote ' + second_target); time.sleep(.2)
            checks['cooldown_survives_map'] = '""' in rcon('g_votedMapName')
        # Short mode cooldowns may expire during the completed-match transition.
        while time.monotonic() - vote_called_at < cooldown + 1:
            time.sleep(min(5, cooldown + 1 - (time.monotonic() - vote_called_at)))
        send('runtime_fixture 0 callvote ' + second_target); time.sleep(4)
        checks['one_human_vote_after_map'] = f'"{second_target}"' in rcon('g_votedMapName')
        send('runtime_fixture 0 bot')
        checks['bad_admin_denied'] = 'Bad rcon' in rcon('bot_killall', 'invalid-fixture')
        checks['admin_bot_killall'] = 'Killed' in rcon('bot_killall')
    finally:
        if proc.poll() is None: send('sv_pure\nquit')
        try: checks[f'exit_{attempt}'] = proc.wait(timeout=10) == 0
        finally:
            if proc.poll() is None: proc.kill(); proc.wait()
            output.close()
for path in home.glob('console-*.log'):
    console = path.read_text(errors='replace')
    checks[path.stem + '_clean'] = not re.search(r'Sys_Error:|script (?:compile|runtime) error|Segmentation fault', console, re.I)
    checks[path.stem + '_headers'] = 'Loaded 8 administrative IWD checksums' in console
result = {'evidence': str(home), 'checks': checks, 'snapshots': snapshots,
          'binary_sha256': hashlib.sha256((home / 'cod4x18_dedrun').read_bytes()).hexdigest()}
(home / 'results.json').write_text(json.dumps(result, indent=2))
print(json.dumps({'evidence': str(home), 'passed': sum(checks.values()),
    'failed': [name for name, passed in checks.items() if not passed],
    'startup_maps': [x['map'] for x in snapshots if x['tag'].startswith('startup')],
    'binary_sha256': result['binary_sha256']}, indent=2))
assert all(checks.values()), 'local runtime qualification failed'
